import test from 'node:test';
import assert from 'node:assert/strict';
import User from '../models/User.js';
import Patient from '../models/Patient.js';
import Appointment from '../models/Appointment.js';
import AuditLog from '../models/AuditLog.js';
import Notification from '../models/Notification.js';
import { createAppointment } from '../controllers/appointmentController.js';
import { notifyAudit } from '../controllers/shared.js';
import { notificationScope } from '../middleware/accessScopes.js';
import { notifications, markNotifications } from '../controllers/settingsController.js';
const doctor = { id: 'doctor', name: 'Synthetic Doctor', role: 'Clinic Staff', active: true, specialty: 'cardiologist', availability: { weekdays: [1], start: '10:00', end: '12:00', duration: 15 } };
const nurse = { id: 'nurse', role: 'Clinic Staff', specialty: 'general-nurse' };
const admin = { id: 'admin', role: 'Administrator', specialty: '' };
const booking = { patientId: 'patient', date: '2099-01-05', time: '10:00', type: 'Consultation' };
const response = { status() { return this; }, json() {} };
test('doctor creation derives assignment, specialty and fixed duration without client fields', async t => {
  let account = doctor, saved;
  t.mock.method(User, 'findById', async id => { assert.equal(id, doctor.id); return account; });
  t.mock.method(User, 'find', () => ({ select: async () => [] }));
  t.mock.method(Patient, 'exists', async () => true);
  t.mock.method(Patient, 'findById', async () => ({ status: 'Active' }));
  t.mock.method(Appointment, 'distinct', async () => []);
  t.mock.method(Appointment, 'find', async () => []);
  t.mock.method(Appointment.collection, 'indexExists', async () => true);
  t.mock.method(Appointment, 'create', async value => { saved = value; return value; });
  t.mock.method(AuditLog, 'create', async value => value);
  await createAppointment({ user: doctor, body: { ...booking, specialty: 'dermatologist', staff: 'Forged name' } }, response);
  assert.equal(saved.staffId, doctor.id); assert.equal(saved.specialty, doctor.specialty); assert.equal(saved.staff, 'Dr. ' + doctor.name); assert.equal(saved.duration, 15);
  await assert.rejects(createAppointment({ user: doctor, body: { ...booking, staffId: 'other' } }, response), error => error.status === 403);
  account = { ...doctor, availability: null };
  await assert.rejects(createAppointment({ user: doctor, body: booking }, response), /availability is not configured/);
  account = { ...doctor, specialty: '' };
  await assert.rejects(createAppointment({ user: doctor, body: booking }, response), error => error.status === 400);
});
test('appointment notifications target admin, intake and the assigned doctor once; no clinical broadcasts', async t => {
  const other = { ...doctor, id: 'other' }, specialty = { ...doctor, id: 'different', specialty: 'dermatologist' };
  t.mock.method(User, 'find', () => ({ select: async () => [admin, nurse, doctor, other, specialty, doctor] }));
  let inserted = [];
  t.mock.method(Notification, 'insertMany', async rows => { inserted.push(...rows); });
  await notifyAudit('Appointment scheduled', 'Patient', booking.patientId, { ...booking, id: 'appointment', staffId: doctor.id, specialty: doctor.specialty, notes: 'CONFIDENTIAL' });
  assert.deepEqual(inserted.map(row => row.userId), ['admin', 'nurse', 'doctor']);
  assert.equal(new Set(inserted.map(row => row.text)).size, 3);
  assert(!JSON.stringify(inserted).includes('CONFIDENTIAL'));
  assert(inserted.every(row => row.scopeVersion === 1 && row.appointmentId === 'appointment'));
  inserted = [];
  await notifyAudit('Consultation created', 'Patient', booking.patientId);
  await notifyAudit('Document uploaded', 'Patient', booking.patientId);
  assert.equal(inserted.length, 0);
  await notifyAudit('Doctor availability updated', 'User', doctor.id);
  assert.deepEqual(inserted.map(row => row.userId), ['admin']);
});
test('list and read operations use identical recipient, role, specialty and current assignment scope', async t => {
  t.mock.method(Appointment, 'distinct', async (field, filter) => { assert.equal(field, 'id'); assert.deepEqual(filter, { staffId: doctor.id, specialty: doctor.specialty }); return ['own']; });
  const scope = await notificationScope(doctor);
  assert.equal(scope.userId, doctor.id); assert.equal(scope.scopeVersion, 1); assert.equal(scope.recipientSpecialty, doctor.specialty);
  assert.deepEqual(scope.$or[0], { appointmentId: { $in: ['own'] } });
  t.mock.method(Notification, 'find', filter => { assert.deepEqual(filter, scope); return { sort() { return this; }, limit: async () => [] }; });
  t.mock.method(Notification, 'updateMany', async (filter, update) => { assert.deepEqual(filter, { ...scope, id: 'other-users-notification' }); assert.deepEqual(update, { $set: { read: true } }); });
  await notifications({ user: doctor }, response);
  await markNotifications({ user: doctor, params: { id: 'other-users-notification' } }, response);
  for (const user of [admin, nurse]) { const filter = await notificationScope(user); assert.equal(filter.userId, user.id); assert.equal(filter.recipientRole, user.role); assert.equal(filter.scopeVersion, 1); }
});

import test from 'node:test';
import assert from 'node:assert/strict';
import bcrypt from 'bcryptjs';
import User from '../models/User.js';
import Counter from '../models/Counter.js';
import AuditLog from '../models/AuditLog.js';
import Notification from '../models/Notification.js';
import Session from '../models/Session.js';
import { createUser } from '../controllers/userController.js';
import { authController } from '../controllers/authController.js';
import { passwordSetupController } from '../utils/passwordSetup.js';
import { resetTokenHash } from '../utils/passwordReset.js';
const config = { jwtSecret: 'synthetic-session-secret-at-least-32-bytes', passwordReset: { clientOrigin: 'https://clinic.example.test', brevo: { apiKey: 'synthetic-key', from: 'accounts@example.test' } } };
const response = () => ({ status(value) { this.code = value; return this; }, cookie() { return this; }, json(value) { this.value = value; } });

test('new accounts use private invitations; setup is bound, expiring, single-use, and enables normal login', async t => {
  let user, sent, sequence = 0;
  t.mock.method(Counter, 'findOneAndUpdate', async () => ({ value: ++sequence }));
  t.mock.method(AuditLog, 'create', async () => ({}));
  t.mock.method(Notification, 'create', async () => ({}));
  t.mock.method(User, 'find', () => ({ select: async () => [] }));
  t.mock.method(User, 'create', async value => { if (user) throw Object.assign(new Error('duplicate'), { code: 11000 }); user = new User(value); return user; });
  t.mock.method(globalThis, 'fetch', async (url, options) => { assert(user); sent = JSON.parse(options.body); return { ok: true, json: async () => ({ messageId: 'synthetic' }) }; });
  const body = { name: 'Synthetic Staff', email: 'staff@example.test', role: 'Clinic Staff', specialty: 'general-nurse' };
  const res = response(); await createUser({ user: { id: 'admin' }, body }, res, config);
  assert.equal(res.code, 201); assert.equal(res.value.welcomeEmailStatus, 'accepted'); assert.equal(user.pendingPasswordSetup, true);
  const token = /#setup-password=([a-f0-9]{64})/.exec(sent.textContent)[1];
  assert.equal(user.passwordSetupHash, resetTokenHash(token)); assert(!user.passwordHash.includes(token));
  assert(user.passwordSetupExpiresAt > new Date());
  for (const field of ['passwordSetupHash', 'passwordSetupEmail', 'passwordSetupVersion', 'passwordSetupExpiresAt', 'invitationRequestedAt']) assert.equal(res.value[field], undefined);
  assert(!JSON.stringify(res.value).includes(token)); assert(sent.textContent.includes('15 minutes')); assert(sent.htmlContent.includes('href="https://clinic.example.test/#setup-password='));
  await assert.rejects(createUser({ user: { id: 'admin' }, body }, response(), config), e => e.code === 11000);
  t.mock.method(User, 'findOneAndUpdate', async (query, update) => {
    assert.equal(query.pendingPasswordSetup, true); assert.equal(query.active, true);
    assert(query.$expr.$and); assert(query.passwordSetupExpiresAt.$gt instanceof Date);
    if (user.passwordSetupHash !== query.passwordSetupHash || !user.pendingPasswordSetup || !user.active || user.passwordSetupExpiresAt <= query.passwordSetupExpiresAt.$gt || user.passwordSetupEmail !== user.email || user.passwordSetupVersion !== user.sessionVersion) return null;
    Object.assign(user, update.$set); user.sessionVersion++; for (const key of Object.keys(update.$unset)) user[key] = undefined;
    return user;
  });
  const controller = passwordSetupController(config);
  const setup = { token, password: 'Synthetic recipient password 42!', confirmPassword: 'Synthetic recipient password 42!', userId: 'another-user' };
  const expires = user.passwordSetupExpiresAt;
  user.passwordSetupExpiresAt = new Date(0);
  await assert.rejects(controller.complete({ body: setup }, response()), e => e.status === 400 && e.message.includes('administrator'));
  user.passwordSetupExpiresAt = expires;
  user.email = 'changed@example.test';
  await assert.rejects(controller.complete({ body: setup }, response()), e => e.status === 400);
  user.email = body.email;
  await assert.rejects(controller.complete({ body: { ...setup, password: 'short', confirmPassword: 'short' } }, response()), e => e.status === 400);
  t.mock.method(User, 'findOne', () => ({ select: async () => user }));
  t.mock.method(user, 'save', async () => user);
  t.mock.method(Session, 'create', async value => value);
  const results = await Promise.allSettled([controller.complete({ body: setup }, response()), controller.complete({ body: setup }, response())]);
  assert.equal(results.filter(item => item.status === 'fulfilled').length, 1);
  assert.equal(user.pendingPasswordSetup, false); assert.equal(user.passwordSetupHash, undefined); assert.equal(user.sessionVersion, 1);
  assert(await bcrypt.compare(setup.password, user.passwordHash)); assert.equal(user.specialty, body.specialty);
  await assert.rejects(controller.complete({ body: setup }, response()), e => e.status === 400);
  const login = response();
  await authController(config).login({ body: { email: user.email, password: setup.password } }, login);
  assert.equal(login.value.user.id, user.id);
  user.pendingPasswordSetup = true;
  await assert.rejects(authController(config).login({ body: { email: user.email, password: setup.password } }, response()), e => e.status === 401);
});

test('invitation resend is admin-only, pending-only and throttled; rotates token and safely handles delivery failure', async t => {
  const user = new User({ _id: 'pending', id: 'pending', email: 'staff@example.test', name: 'Synthetic', role: 'Clinic Staff', specialty: 'general-nurse', pendingPasswordSetup: true, active: true, invitationRequestedAt: new Date(0), passwordSetupHash: 'old' });
  let fail = false, calls = 0;
  t.mock.method(console, 'error', () => {});
  t.mock.method(AuditLog, 'create', async () => ({}));
  t.mock.method(User, 'findById', () => ({ select: async () => user }));
  t.mock.method(User, 'findOneAndUpdate', async (query, update) => {
    assert.equal(query.pendingPasswordSetup, true); assert(query.$expr);
    if (user.invitationRequestedAt > query.$or[1].invitationRequestedAt.$lte) return null;
    Object.assign(user, update.$set); return user;
  });
  t.mock.method(User, 'updateOne', async (query, update) => { assert.equal(query.passwordSetupHash, user.passwordSetupHash); for (const key of Object.keys(update.$unset)) user[key] = undefined; return { modifiedCount: 1 }; });
  t.mock.method(globalThis, 'fetch', async () => { calls++; return fail ? { ok: false, status: 401 } : { ok: true, json: async () => ({ messageId: 'synthetic' }) }; });
  const controller = passwordSetupController(config);
  const req = { user: { id: 'admin', role: 'Administrator' }, params: { id: user.id } };
  await assert.rejects(controller.resend({ ...req, user: { role: 'Clinic Staff' } }, response()), e => e.status === 403);
  user.pendingPasswordSetup = false;
  await assert.rejects(controller.resend(req, response()), e => e.status === 409); assert.equal(calls, 0);
  user.pendingPasswordSetup = true;
  const result = response(); await controller.resend(req, result);
  assert.equal(result.value.welcomeEmailStatus, 'accepted'); assert.notEqual(user.passwordSetupHash, 'old');
  await assert.rejects(controller.resend(req, response()), e => e.status === 409); assert.equal(calls, 1);
  user.invitationRequestedAt = new Date(0); fail = true;
  const failed = response(); await controller.resend(req, failed);
  assert.equal(failed.value.welcomeEmailStatus, 'failed'); assert.equal(user.pendingPasswordSetup, true); assert.equal(user.passwordSetupHash, undefined);
});

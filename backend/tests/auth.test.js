import test from 'node:test';
import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import bcrypt from 'bcryptjs';
import jwt from 'jsonwebtoken';
import User from '../models/User.js';
import Session from '../models/Session.js';
import AuditLog from '../models/AuditLog.js';
import { authController } from '../controllers/authController.js';

test('bcrypt login rejects incorrect/inactive accounts and issues a revocable secure session', async t => {
  const supplied = randomBytes(16).toString('hex');
  const hash = await bcrypt.hash(supplied, 12);
  assert.equal(await bcrypt.compare(supplied, hash), true);
  assert.equal(await bcrypt.compare(supplied + 'x', hash), false);
  const user = new User({ _id: 'auth-test', id: 'auth-test', name: 'Test Administrator', email: 'admin@example.test', passwordHash: hash, role: 'Administrator', active: true, sessionVersion: 0 });
  t.mock.method(user, 'save', async () => user);
  let found = user, lookup, cookie, result, storedSession, deletedSession;
  t.mock.method(User, 'findOne', query => { lookup = query; return { select: async () => found }; });
  t.mock.method(Session, 'create', async value => { storedSession = value; return value; });
  t.mock.method(Session, 'deleteOne', async value => { deletedSession = value; });
  t.mock.method(AuditLog, 'create', async value => { assert(!JSON.stringify(value).includes(supplied)); assert(!JSON.stringify(value).includes(hash)); return value; });
  const config = { jwtSecret: randomBytes(48).toString('hex'), production: false };
  const controller = authController(config);
  const res = { cookie(name, token, options) { cookie = { name, token, options }; return this; }, clearCookie() { return this; }, json(value) { result = value; } };
  const request = password => ({ body: { email: ' ADMIN@EXAMPLE.TEST ', password } });
  await assert.rejects(() => controller.login(request(supplied + 'x'), res), error => error.status === 401);
  user.active = false;
  await assert.rejects(() => controller.login(request(supplied), res), error => error.status === 401);
  user.active = true; found = null;
  await assert.rejects(() => controller.login(request(supplied), res), error => error.status === 401);
  found = user;
  await controller.login(request(supplied), res);
  assert.equal(lookup.email, 'admin@example.test');
  assert.equal(cookie.options.httpOnly, true);
  assert.equal(cookie.options.sameSite, 'lax');
  assert.equal(cookie.options.path, '/api');
  const claims = jwt.verify(cookie.token, config.jwtSecret, { algorithms: ['HS256'], issuer: 'careline', audience: 'careline-web' });
  assert.equal(claims.sub, user.id);
  assert.equal(claims.jti, storedSession._id);
  assert.equal(result.csrfToken, storedSession.csrf);
  assert.equal(result.user.toJSON().passwordHash, undefined);
  await controller.logout({ user, session: { id: storedSession._id } }, res);
  assert.equal(deletedSession._id, storedSession._id);
});

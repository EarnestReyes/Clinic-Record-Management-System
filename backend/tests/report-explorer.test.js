test('record pipeline paginates stable results, counts before pagination and projects no clinical fields', () => {
  for (const type of Object.keys(reportDimensions)) {
    const config = explorerQuery(type,{ ...range,page: '2',limit: '25',sort: 'id',direction: 'asc' },{ staffId: 'own' });
    const pipeline = recordsPipeline(type,config);
    assert.deepEqual(pipeline[0], { $match: config.match });
    assert.deepEqual(pipeline[2].$sort,{ reference: 1,id: 1 });
    const facet = pipeline[3].$facet;
    assert.deepEqual(facet.total,[{ $count: 'value' }]);
    assert.deepEqual(facet.items.slice(0,2),[{ $skip: 25 },{ $limit: 25 }]);
    const projection = facet.items.at(-1).$project;
    for (const field of ['diagnosis','treatment','notes','complaint','details','dob','phone','email','allergies']) assert(!projection[field]);
    assert.deepEqual(recordsPipeline(type,config,true)[3].$facet.items[0],{ $limit: 10001 });
  }
});

test('summary, paginated records and CSV retain doctor scope; no broad clinical read is used', async t => {
  const doctor = { id: 'doctor', role: 'Clinic Staff', specialty: 'cardiologist' };
  const rows = [{ id: 'own', staffId: 'doctor', specialty: 'cardiologist', date: '2026-02-01', status: 'Cancelled', notes: 'PRIVATE', diagnosis: 'PRIVATE' }, { id: 'other', staffId: 'other', specialty: 'cardiologist', date: '2026-02-01', status: 'Cancelled' }];
  let calls = 0;
  t.mock.method(Appointment,'aggregate',pipeline => ({ option: async options => {
    assert.equal(options.maxTimeMS,10000); assert.deepEqual(pipeline[0].$match.$and[0],{ staffId: 'doctor', specialty: 'cardiologist' }); calls++;
    const matching = rows.filter(row => matches(row,pipeline[0].$match));
    if (pipeline[1].$facet) return [groupsFor('appointments',matching)];
    const projection = pipeline[3].$facet.items.at(-1).$project;
    return [{ total: [{ value: matching.length }], items: matching.map(row => Object.fromEntries(Object.keys(projection).filter(key => projection[key] && row[key] !== undefined).map(key => [key,row[key]]))) }];
  } }));
  t.mock.method(Appointment,'find',() => { throw new Error('Unbounded find must not be used'); });
  t.mock.method(AuditLog,'create',async () => ({}));
  for (const mode of ['summary','records']) {
    let output;
    await report({ user: doctor,params: { type: 'appointments' },query: { ...range,mode,staffId: 'other',filter: JSON.stringify({ field: 'status', value: 'Cancelled' }) } }, { json: value => { output = value; } });
    assert.equal(mode === 'summary' ? output.analytics.total : output.total,1);
    assert(!JSON.stringify(output).includes('PRIVATE'));
  }
  let bytes;
  await report({ user: doctor,params: { type: 'appointments' },query: { ...range,mode: 'records',format: 'csv',filter: JSON.stringify({ field: 'status', value: 'Cancelled' }) } },{ set() { return this; },send(value) { bytes = value; } });
  assert(bytes.includes('own')); assert(!bytes.includes('other')); assert(!bytes.includes('PRIVATE')); assert.equal(calls,3);
});

test('patient and consultation scopes compose with filters and unauthorized roles are denied', async t => {
  const doctor = { id: 'doctor',role: 'Clinic Staff',specialty: 'cardiologist' };
  t.mock.method(Appointment,'distinct',async () => ['scheduled']);
  t.mock.method(Patient,'distinct',async () => ['assigned']);
  for (const [type,model] of [['patients',Patient],['consultations',Consultation],['activity',AuditLog]]) {
    t.mock.method(model,'aggregate',pipeline => ({ option: async () => {
      const scope = pipeline[0].$match.$and[0];
      if (type === 'patients') assert.deepEqual(scope.$or,[{ assignedStaffId: 'doctor' },{ id: { $in: ['scheduled'] } }]);
      if (type === 'consultations') assert.deepEqual(scope,{ staffId: 'doctor',specialty: 'cardiologist',patientId: { $in: ['assigned'] } });
      if (type === 'activity') { assert.equal(scope.actorId,'doctor'); assert(scope.$or); }
      return [{ items: [],total: [] }];
    } }));
    let output;
    await report({ user: doctor,params: { type },query: { ...range,mode: 'records' } },{ json: value => { output = value; } });
    assert.equal(output.total,0); assert.deepEqual(output.items,[]);
  }
  await assert.rejects(report({ user: { role: 'Clinic Staff',specialty: 'general-nurse' },params: { type: 'consultations' },query: { ...range,mode: 'records' } },{}),error => error.status === 403);
});


// Evaluate only the query expressions generated by this feature against synthetic records.
function expression(value, row, variables = {}) {
  if (typeof value === 'string') return value.startsWith('$$') ? variables[value.slice(2)] : value.startsWith('$') ? row[value.slice(1)] : value;
  if (Array.isArray(value)) return value.map(item => expression(item, row, variables));
  if (!value || typeof value !== 'object') return value;
  const evaluate = item => expression(item, row, variables);
  if ('$literal' in value) return value.$literal;
  if ('$ifNull' in value) { const [a,b] = evaluate(value.$ifNull); return a ?? b; }
  if ('$trim' in value) return evaluate(value.$trim.input).trim();
  if ('$let' in value) return expression(value.$let.in, row, { ...variables, ...Object.fromEntries(Object.entries(value.$let.vars).map(([key,item]) => [key,evaluate(item)])) });
  if ('$cond' in value) { const [condition,a,b] = value.$cond; return evaluate(evaluate(condition) ? a : b); }
  if ('$eq' in value) { const [a,b] = evaluate(value.$eq); return a === b; }
  if ('$in' in value) { const [a,b] = evaluate(value.$in); return b.includes(a); }
  if ('$not' in value) return !evaluate(value.$not[0]);
  throw new Error('Unexpected expression ' + JSON.stringify(value));
}
function matches(row, filter) {
  return Object.entries(filter).every(([key, value]) => {
    if (key === '$and') return value.every(item => matches(row,item));
    if (key === '$or') return value.some(item => matches(row,item));
    if (key === '$expr') return expression(value,row);
    if (!value || typeof value !== 'object') return row[key] === value;
    if ('$gte' in value) return row[key] >= value.$gte && row[key] <= value.$lte;
    if ('$regex' in value) return new RegExp(value.$regex, value.$options).test(row[key] || '');
    if ('$in' in value) return value.$in.includes(row[key]);
    if ('$exists' in value) return (row[key] !== undefined) === value.$exists;
    throw new Error('Unexpected condition');
  });
}
function groupsFor(type, rows) {
  const group = key => {
    const counts = new Map();
    for (const row of rows) { const value = key === 'dates' ? clinicDate(type === 'patients' ? row.created : row.date) : String(row[key] || '').trim() || unknownCategory; counts.set(value,(counts.get(value) || 0) + 1); }
    return [...counts].map(([_id,value]) => ({ _id,value }));
  };
  return { total: rows.length ? [{ value: rows.length }] : [], dates: group('dates'), ...Object.fromEntries(reportDimensions[type].map(([field]) => [field,group(field)])) };
}

test('every record KPI and chart bucket reconciles with server filters, including combined categories and partial months', () => {
  const rows = Array.from({ length: 45 }, (_, index) => ({ id: String(index), created: index % 2 ? '2026-01-16' : '2026-12-19', date: index % 2 ? '2026-01-16' : '2026-12-19', gender: index % 2 ? 'Female' : 'Male', status: ['Scheduled','Completed','Cancelled','No Show'][index % 4], specialty: index === 0 ? ' ' : `specialty ${index % 12}`, type: `type ${index % 12}`, action: `action ${index % 12}` }));
  for (const type of Object.keys(reportDimensions)) {
    const typedRows = type === 'activity' ? rows.map(row => ({ ...row, date: new Date(row.date + 'T12:00:00+08:00') })) : rows;
    const analytics = reportAnalytics(type, [], { ...range, groups: groupsFor(type,typedRows) });
    for (const metric of [...analytics.summary.filter(item => item.filter), ...analytics.charts.flatMap(chart => chart.points)]) {
      const config = explorerQuery(type, { ...range, filter: JSON.stringify(metric.filter) }, {});
      assert.equal(typedRows.filter(row => matches(row,config.match)).length, metric.value, `${type}: ${metric.label}`);
    }
    const empty = reportAnalytics(type, [], { ...range, groups: groupsFor(type,[]) });
    assert.equal(empty.total,0); assert.deepEqual(empty.charts,[]);
  }
  const chart = reportAnalytics('appointments',rows,range).charts[0];
  assert.deepEqual(chart.points[0].filter, { from: '2026-01-15', to: '2026-01-31' });
  assert.deepEqual(chart.points.at(-1).filter, { from: '2026-12-01', to: '2026-12-20' });
});

test('Manila event boundaries, grouped daily periods, literal categories and escaped search stay exact', () => {
  const query = { from: '2026-10-16', to: '2026-10-16' };
  const config = explorerQuery('activity',query,{});
  const events = ['2026-10-15T15:59:59.999Z','2026-10-15T16:00:00Z','2026-10-16T15:59:59.999Z','2026-10-16T16:00:00Z'].map(date => ({ date: new Date(date) }));
  assert.deepEqual(events.map(row => matches(row,config.match)),[false,true,true,false]);
  assert.equal(summaryPipeline('activity',config.match)[1].$facet.dates[0].$group._id.$dateToString.timezone,'Asia/Manila');
  const rows = Array.from({ length: 32 }, (_,i) => ({ date: `2026-01-${String(i % 31 + 1).padStart(2,'0')}`, status: 'Scheduled' }));
  for (const point of reportAnalytics('appointments',rows,{ from: '2026-01-01', to: '2026-02-01' }).charts[0].points) {
    assert.equal(rows.filter(row => matches(row,explorerQuery('appointments',{ from: '2026-01-01', to: '2026-02-01', filter: JSON.stringify(point.filter) },{}).match)).length,point.value);
  }
  const literal = explorerQuery('activity',{ ...range, filter: JSON.stringify({ field: 'action', value: '$secret' }), search: '[x]' },{});
  assert(matches({ date: new Date('2026-02-01T00:00:00Z'), action: '$secret', id: '[x]' },literal.match));
  assert(!matches({ date: new Date('2026-02-01T00:00:00Z'), action: '$secret', id: 'x' },literal.match));
});

